"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const {fields,status,changed}=require("./sync_airtable_support_candidates");
const real=JSON.parse(fs.readFileSync("data/priority_projects.json","utf8"))
 .filter(x=>x.priorityCategory==="arts_content_support");
assert(real.length>=1,"At least one eligible source record required");
const first=real[0],mapped=fields(first);
assert.equal(mapped["flddGu8HySNRqIoyJ"],"live-"+first.id);
assert.equal(mapped["fldNCe5SdjlOFVB7O"],first.title);
assert.equal(typeof mapped["fldjA4F9QIT9wHyfN"],"number");
assert(!("fldOGZ0bZVCV1hNnQ" in mapped),"Do not reset human selection");
assert(!("fldKNS0du4E4Pl68X" in mapped),"Do not reset registration status");
assert(!("fld1cpoKVjtRkq7Z2" in mapped),"Do not alter linked application");
assert.equal(changed(mapped,mapped),false,"Skip identical candidate updates");
assert.equal(changed({...mapped,fldKNS0du4E4Pl68X:"등록 완료"},mapped),false,"Ignore team-managed fields");
assert.equal(changed({...mapped,fldNCe5SdjlOFVB7O:"OLD NAME"},mapped),true,"Update changed official metadata");
assert.equal(status({deadline:"2025-01-01"}),"마감");
assert.equal(status({deadline:"2099-01-01",verificationStatus:"source_unavailable"}),"원문 재확인");
assert.equal(status({deadline:"2099-01-01",startDate:"2098-01-01"}),"접수 예정");
assert.equal(status({deadline:"2099-01-01",startDate:"2020-01-01"}),"기간상 접수 가능");
assert.ok(mapped["fldkvwwF165BU1L4r"]?.startsWith("https://")||!mapped["fldkvwwF165BU1L4r"]);
console.log("Airtable mirror checks passed; source-only fields, no staff work overwritten; "+real.length+" public candidates");
